def text(S, x, y, s, color, scale=1):
    cx = x
    for ch in s.upper():
        g = G.get(ch, G['?'])
        for i, bit in enumerate(g):
            if bit == '1':
                for a in range(scale):
                    for b in range(scale):
                        S.set(cx + (i % 3) * scale + a, y + (i // 3) * scale + b, color)
        cx += 4 * scale
    return cx - x


def width(s, scale=1):
    return len(s) * 4 * scale - scale
